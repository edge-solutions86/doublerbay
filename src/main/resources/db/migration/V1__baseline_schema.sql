-- The baseline schema: the register, the damage cards and their dispositions, and the decisions
-- made about them. Every constraint and index is named, because an unnamed one cannot be dropped
-- on every database, and a schema that can only be built forwards cannot be rolled back.

CREATE TABLE aircraft (
    serial VARCHAR(8) NOT NULL,
    registration VARCHAR(8) NOT NULL,
    series VARCHAR(8) NOT NULL,
    line_number INTEGER NOT NULL,
    delivered DATE NOT NULL,
    withdrawn DATE,
    recorded_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_aircraft PRIMARY KEY (serial)
);
CREATE INDEX ix_aircraft_registration ON aircraft (registration);

CREATE TABLE deferral (
    against VARCHAR(16) NOT NULL,
    granted DATE NOT NULL,
    at_cycles INTEGER NOT NULL,
    at_hours INTEGER NOT NULL,
    limit_cycles INTEGER,
    limit_hours INTEGER,
    limit_months INTEGER,
    limit_days INTEGER,
    method VARCHAR(32) NOT NULL,
    granted_by VARCHAR(64) NOT NULL,
    reason VARCHAR(256) NOT NULL,
    lifted DATE,
    recorded_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_deferral PRIMARY KEY (against)
);
CREATE INDEX ix_deferral_granted ON deferral (granted);

CREATE TABLE disposition (
    reference VARCHAR(16) NOT NULL,
    state VARCHAR(24) NOT NULL,
    recorded_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_disposition PRIMARY KEY (reference)
);
CREATE INDEX ix_disposition_state ON disposition (state);

CREATE TABLE engineering_order (
    reference VARCHAR(16) NOT NULL,
    against VARCHAR(16) NOT NULL,
    question VARCHAR(512) NOT NULL,
    raised DATE NOT NULL,
    state VARCHAR(16) NOT NULL,
    sent DATE,
    answered DATE,
    sheet VARCHAR(16),
    approved_category VARCHAR(1),
    valid_until DATE,
    recorded_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_engineering_order PRIMARY KEY (reference),
    CONSTRAINT uq_engineering_order_against UNIQUE (against, raised)
);
CREATE INDEX ix_engineering_order_against ON engineering_order (against);
CREATE INDEX ix_engineering_order_raised ON engineering_order (raised);
CREATE INDEX ix_engineering_order_state ON engineering_order (state);

CREATE TABLE corrosion_entry (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    serial VARCHAR(8) NOT NULL,
    against VARCHAR(16) NOT NULL,
    part VARCHAR(16) NOT NULL,
    level INTEGER NOT NULL,
    found_on DATE NOT NULL,
    reported_on DATE,
    recorded_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_corrosion_entry PRIMARY KEY (id),
    CONSTRAINT fk_corrosion_entry_serial_aircraft FOREIGN KEY (serial) REFERENCES aircraft (serial)
);
CREATE INDEX ix_corrosion_entry_against ON corrosion_entry (against);
CREATE INDEX ix_corrosion_entry_found_on ON corrosion_entry (found_on);
CREATE INDEX ix_corrosion_entry_level ON corrosion_entry (level);
CREATE INDEX ix_corrosion_entry_part ON corrosion_entry (part);
CREATE INDEX ix_corrosion_entry_serial ON corrosion_entry (serial);

CREATE TABLE disposition_move (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    reference VARCHAR(16) NOT NULL,
    sequence INTEGER NOT NULL,
    was VARCHAR(24) NOT NULL,
    now VARCHAR(24) NOT NULL,
    "on" DATE NOT NULL,
    by VARCHAR(64) NOT NULL,
    note VARCHAR(256) NOT NULL,
    reopened BOOLEAN NOT NULL,
    recorded_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_disposition_move PRIMARY KEY (id),
    CONSTRAINT fk_disposition_move_reference_disposition FOREIGN KEY (reference) REFERENCES disposition (reference),
    CONSTRAINT uq_disposition_move_reference UNIQUE (reference, sequence)
);

CREATE TABLE embodiment (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    serial VARCHAR(8) NOT NULL,
    chapter INTEGER NOT NULL,
    number INTEGER NOT NULL,
    recorded_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_embodiment PRIMARY KEY (id),
    CONSTRAINT fk_embodiment_serial_aircraft FOREIGN KEY (serial) REFERENCES aircraft (serial),
    CONSTRAINT uq_embodiment_serial UNIQUE (serial, chapter, number)
);

CREATE TABLE finding (
    reference VARCHAR(16) NOT NULL,
    revision INTEGER NOT NULL,
    serial VARCHAR(8) NOT NULL,
    kind VARCHAR(24) NOT NULL,
    found_on DATE NOT NULL,
    source VARCHAR(32) NOT NULL,
    origin VARCHAR(24) NOT NULL,
    at_cycles INTEGER NOT NULL,
    at_hours INTEGER NOT NULL,
    structure VARCHAR(8) NOT NULL,
    frame INTEGER,
    aft_of_frame INTEGER,
    stringer INTEGER,
    below_stringer INTEGER,
    rib INTEGER,
    outboard_of_rib INTEGER,
    spar VARCHAR(8),
    aft_of_spar INTEGER,
    surface VARCHAR(8),
    side VARCHAR(1) NOT NULL,
    measurements VARCHAR(4096) NOT NULL,
    superseded_by VARCHAR(16),
    note VARCHAR(256) NOT NULL,
    recorded_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_finding PRIMARY KEY (reference, revision),
    CONSTRAINT fk_finding_serial_aircraft FOREIGN KEY (serial) REFERENCES aircraft (serial)
);
CREATE INDEX ix_finding_found_on ON finding (found_on);
CREATE INDEX ix_finding_kind ON finding (kind);
CREATE INDEX ix_finding_serial ON finding (serial);

CREATE TABLE reading (
    serial VARCHAR(8) NOT NULL,
    taken DATE NOT NULL,
    cycles INTEGER NOT NULL,
    hours INTEGER NOT NULL,
    recorded_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_reading PRIMARY KEY (serial, taken),
    CONSTRAINT fk_reading_serial_aircraft FOREIGN KEY (serial) REFERENCES aircraft (serial)
);

CREATE TABLE repair (
    reference VARCHAR(16) NOT NULL,
    serial VARCHAR(8) NOT NULL,
    part VARCHAR(16) NOT NULL,
    against VARCHAR(16) NOT NULL,
    form VARCHAR(24) NOT NULL,
    category VARCHAR(1) NOT NULL,
    sealed BOOLEAN NOT NULL,
    page VARCHAR(16) NOT NULL,
    material VARCHAR(24) NOT NULL,
    gauge INTEGER NOT NULL,
    along INTEGER NOT NULL,
    around INTEGER NOT NULL,
    filler INTEGER,
    fastener_dash INTEGER NOT NULL,
    rows_each_side INTEGER NOT NULL,
    per_row INTEGER NOT NULL,
    pitch INTEGER NOT NULL,
    row_spacing INTEGER NOT NULL,
    edge_distance INTEGER NOT NULL,
    centre_along INTEGER NOT NULL,
    centre_around INTEGER NOT NULL,
    embodied DATE NOT NULL,
    at_cycles INTEGER NOT NULL,
    at_hours INTEGER NOT NULL,
    removed DATE,
    recorded_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_repair PRIMARY KEY (reference),
    CONSTRAINT fk_repair_serial_aircraft FOREIGN KEY (serial) REFERENCES aircraft (serial)
);
CREATE INDEX ix_repair_against ON repair (against);
CREATE INDEX ix_repair_category ON repair (category);
CREATE INDEX ix_repair_embodied ON repair (embodied);
CREATE INDEX ix_repair_part ON repair (part);
CREATE INDEX ix_repair_serial ON repair (serial);

CREATE TABLE inspection (
    against VARCHAR(16) NOT NULL,
    part VARCHAR(16) NOT NULL,
    method VARCHAR(32) NOT NULL,
    threshold_cycles INTEGER,
    threshold_months INTEGER,
    repeat_cycles INTEGER,
    embodied DATE NOT NULL,
    at_cycles INTEGER NOT NULL,
    at_hours INTEGER NOT NULL,
    last_done DATE,
    last_cycles INTEGER,
    last_hours INTEGER,
    recorded_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_inspection PRIMARY KEY (against),
    CONSTRAINT fk_inspection_against_repair FOREIGN KEY (against) REFERENCES repair (reference)
);
CREATE INDEX ix_inspection_last_done ON inspection (last_done);
